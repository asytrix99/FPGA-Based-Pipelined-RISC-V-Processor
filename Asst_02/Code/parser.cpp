int open_serial_port(const char* device)
{
    int fd = open(device, O_RDWR | O_NOCTTY);

    if (fd < 0)
    {
        std::cerr << "Failed to open serial port: "
                  << device << '\n';

        return -1;
    }

    termios tty{};

    if (tcgetattr(fd, &tty) != 0)
    {
        std::cerr << "Failed to get serial port settings\n";
        close(fd);
        return -1;
    }

    // Change this if your FPGA uses another baud rate
    cfsetispeed(&tty, B115200);
    cfsetospeed(&tty, B115200);

    tty.c_cflag |= (CLOCAL | CREAD);

    // 8 data bits
    tty.c_cflag &= ~CSIZE;
    tty.c_cflag |= CS8;

    // No parity
    tty.c_cflag &= ~PARENB;

    // 1 stop bit
    tty.c_cflag &= ~CSTOPB;

    // No hardware flow control
    tty.c_cflag &= ~CRTSCTS;

    // Raw mode
    tty.c_lflag = 0;
    tty.c_oflag = 0;
    tty.c_iflag = 0;

    // Blocking read
    tty.c_cc[VMIN] = 1;
    tty.c_cc[VTIME] = 0;

    if (tcsetattr(fd, TCSANOW, &tty) != 0)
    {
        std::cerr << "Failed to configure serial port\n";
        close(fd);
        return -1;
    }

    tcflush(fd, TCIFLUSH);

    return fd;
}


bool uart_read_byte(int fd, uint8_t& byte) {
    ssize_t res = read(fd, &byte, 1);

    return res == 1;
}

bool receive_packet(int fd, TPacket& packet) {
    std::array<uint8_t, PACKET_SIZE> buffer{};

    while(true) {
        uint8_t byte;

        // loop until find magic
        while(true) {
            if(!uart_read_byte(fd, byte)) return false;
            if (byte == MAGIC) break;

            // Print all non packet data
            std::cout << static_cast<char>(byte);
        }

        buffer[0] = MAGIC;

        for (size_t i = 1; i < PACKET_SIZE; ++i) {
            if (!uart_read_byte(fd, buffer[i])) {
                return false;
            }
        }


        if (parse_packet(buffer, packet)) {
            return true;
        }
    }
}

void print_packet(const TPacket& packet) {
    std::cout << std::endl << "Magic: 0x"
              << std::hex << std::uppercase
              << packet.magic
              << '\n';

    std::cout << "Checksum: 0x"
              << packet.check_sum
              << '\n';

    std::cout << "Raw data: 0x"
              << packet.raw_data
              << std::dec
              << '\n';

    // Extract X, Y, Z bytes
    uint8_t x_raw = (packet.raw_data >> 16) & 0xFF;
    uint8_t y_raw = (packet.raw_data >> 8) & 0xFF;
    uint8_t z_raw = packet.raw_data & 0xFF;

    // Interpret them as signed 8-bit values
    int8_t x = static_cast<int8_t>(x_raw);
    int8_t y = static_cast<int8_t>(y_raw);
    int8_t z = static_cast<int8_t>(z_raw);

    std::cout << "X: " << static_cast<int>(x) << '\n';
    std::cout << "Y: " << static_cast<int>(y) << '\n';
    std::cout << "Z: " << static_cast<int>(z) << '\n';

    std::cout << "X scaled: "
              << packet.x_scaled
              << '\n';

    std::cout << "Y scaled: "
              << packet.y_scaled
              << '\n';

    std::cout << "Z scaled: "
              << packet.z_scaled
              << '\n';
}


int main(int argc, char** argv) {
    if (argc != 2) {
        std::cerr << "Usage: " << argv[0] << " /dev/ttyUSB0" << std::endl;

        return 1;
    }

    const char* serial_device = argv[1];

    int serial_fd = open_serial_port(serial_device);

    if (serial_fd < 0) return 1;

    TPacket packet{};

    while(true) {
        if (receive_packet(serial_fd, packet)) {
            print_packet(packet);
        }
    }

    close(serial_fd);

    return 0;
}
