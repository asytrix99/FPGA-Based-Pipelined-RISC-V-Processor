module MCycle

    #(parameter width = 4,
      parameter BOOTH = 1) // Keep this at 4 to verify your algorithms with 4 bit numbers (easier). When using MCycle as a component in ARM, generic map it to 32.
      // BOOTH = 1: signed multiply, BOOTH = 0: original signed multiply
    (
        input CLK,
        input RESET, // Connect this to the reset of the ARM processor.
        input Start, // Multi-cycle Enable. The control unit should assert this when an instruction with a multi-cycle operation is detected.
        input [1:0] MCycleOp, // Multi-cycle Operation. "00" for signed multiplication, "01" for unsigned multiplication, "10" for signed division, "11" for unsigned division. Generated by Control unit
        input [width-1:0] Operand1, // Multiplicand / Dividend
        input [width-1:0] Operand2, // Multiplier / Divisor
        output reg [width-1:0] Result1, // LSW of Product / Quotient
        output reg [width-1:0] Result2, // MSW of Product / Remainder
        output reg Busy // Set immediately when Start is set. Cleared when the Results become ready. This bit can be used to stall the processor while multi-cycle operations are on.
    );
    
// use the Busy signal to reset WE_PC to 0 in ARM.v (aka "freeze" PC). The two signals are complements of each other
// since the IDLE_PROCESS is combinational, instantaneously asserts Busy once Start is asserted
  
    // change to localparam to be explicit since parameter is used in header
    localparam IDLE = 1'b0 ;
    localparam COMPUTING = 1'b1 ;
    
    reg state = IDLE ;
    reg n_state = IDLE ;
    reg done ;
    reg [7:0] count = 0 ; // assuming no computation takes more than 256 cycles.
    reg [2*width-1:0] temp_sum = 0 ;
    reg [2*width-1:0] shifted_op1 = 0 ;
    reg [2*width-1:0] shifted_op2 = 0 ;     
    
    // booth registers
    reg [2*width:0] booth_p = 0; // { acc[width], multiplier[width], q_minus1[1]} (2*width+1 bits)
    reg [width-1:0] booth_a = 0; // multiplicand A, never shift (width bits)
    reg [width:0] booth_sum; // acc -> 1 bit wider, compensate for overflow
    reg [2*width+1:0] booth_tmp; // placeholder before right shift
    
    // Divide operand
    reg [width-1:0] div_dividend;
    reg [width-1:0] div_divisor;
    reg [width-1:0] div_quotient;
    reg [width-1:0] div_remainder;
    
    reg div_quotient_sign;
    reg div_remainder_sign;
   
    always@( state, done, Start, RESET ) begin : IDLE_PROCESS  
		// Note : This block uses non-blocking assignments to get around an unpredictable Verilog simulation behaviour.
        // default outputs
        Busy <= 1'b0 ;
        n_state <= IDLE ;
        
        // reset
        if(~RESET)
            case(state)
                IDLE: begin
                    if(Start) begin // note: a mealy machine, since output depends on current state (IDLE) & input (Start)
                        n_state <= COMPUTING ;
                        Busy <= 1'b1 ;
                    end
                end
                COMPUTING: begin
                    if(~done) begin
                        n_state <= COMPUTING ;
                        Busy <= 1'b1 ;
                    end
                end        
            endcase    
    end


    always@( posedge CLK ) begin : STATE_UPDATE_PROCESS // state updating
        state <= n_state ;    
    end    
    
    always@( posedge CLK ) begin : COMPUTING_PROCESS // process which does the actual computation
        // n_state == COMPUTING and state == IDLE implies we are just transitioning into COMPUTING
        if( RESET | (n_state == COMPUTING & state == IDLE) ) begin // 2nd condition is true during the very 1st clock cycle of the multiplication
            count = 0 ;
            temp_sum = 0 ;
            
            if ( ~MCycleOp[1] ) begin // Multiply
                shifted_op1 = { {width{~MCycleOp[0] & Operand1[width-1]}}, Operand1 } ; // sign extend the operands  
                shifted_op2 = { {width{~MCycleOp[0] & Operand2[width-1]}}, Operand2 } ; 
                booth_p = { {width{1'b0}}, Operand2, 1'b0 };
                booth_a = Operand1;
            end 
            
            else begin // Divide
                if (~MCycleOp[0]) begin // Signed division
                    div_dividend = Operand1[width-1] ? ~Operand1 + 1'b1 : Operand1;
                    div_divisor = Operand2[width-1] ? ~Operand2 + 1'b1 : Operand2;
                    div_quotient_sign = Operand1[width-1] ^ Operand2[width-1];
                    div_remainder_sign = Operand1[width-1];
                end
                else begin
                    div_dividend = Operand1;
                    div_divisor = Operand2;
                    div_quotient_sign = 0;
                    div_remainder_sign = 0;
                end
                div_quotient = 0;
                div_remainder = 0;
            end
        end
        done <= 1'b0 ;   
        
        if( ~MCycleOp[1] ) begin // Multiply
            // signed multiply
            if (~MCycleOp[0] & (BOOTH != 0)) begin
                if (n_state == COMPUTING) begin
                    // 01 -> end of run of 1s -> acc = acc + A
                    // 10 -> start of run of 1s -> acc = acc - A
                    // 00 / 11 -> nothing, middle of run of 00's/11's
                    // sign extend acc & A by 1 bit to compensate for overflow
                    case (booth_p[1:0])
                        2'b01: booth_sum = {booth_p[2*width], booth_p[2*width:width+1]} + {booth_a[width-1], booth_a};
                        2'b10: booth_sum = {booth_p[2*width], booth_p[2*width:width+1]} - {booth_a[width-1], booth_a};
                        default: booth_sum = {booth_p[2*width], booth_p[2*width:width+1]};
                    endcase
                    booth_tmp = { booth_sum, booth_p[width:0] }; // combine all -> { new acc, multiplier A, q_minus1 }  
                    booth_p = booth_tmp[2*width+1:1]; // right shift, drop q_minus1
                    temp_sum = booth_p[2*width:1]; // product so far = { acc, multiplier A }
                    
                    if (count == width-1)
                        done <= 1'b1;
                    count = count + 1;
                end
            end
            
            // unsigned multiply  
            else begin 
                if( shifted_op2[0] ) // add only if b0 = 1
                    temp_sum = temp_sum + shifted_op1 ; // partial product for multiplication
                
                shifted_op2 = {1'b0, shifted_op2[2*width-1 : 1]} ;
                shifted_op1 = {shifted_op1[2*width-2 : 0], 1'b0} ;    
                
                if( (MCycleOp[0] & count == width-1) | (~MCycleOp[0] & count == 2*width-1) ) // last cycle?
                    done <= 1'b1 ;   
                   
                count = count + 1;    
            end    
        end
        
        else begin // Supposed to be Divide. The dummy code below takes 1 cycle to execute, just returns the operands. Change this to signed [ if(~MCycleOp[0]) ] and unsigned [ if(MCycleOp[0]) ] division.
            div_remainder = {div_remainder[width-2 : 0], div_dividend[width-1]};
            div_dividend = {div_dividend[width-2 : 0], 1'b0};                       // left shift
            
            if (div_remainder >= div_divisor) begin
                div_remainder = div_remainder - div_divisor;
                div_quotient = {div_quotient[width-2:0], 1'b1};
            end
            else begin
                div_quotient = {div_quotient[width-2:0], 1'b0};
            end
            
            if (count == width-1) begin
                temp_sum[width-1:0] = div_quotient_sign ? ~div_quotient + 1'b1 : div_quotient;
                temp_sum[2*width-1:width] = div_remainder_sign ? ~div_remainder + 1'b1 : div_remainder;
                done <= 1'b1;
            end
            else begin
                count = count + 1;
            end
        end
        
        Result2 <= temp_sum[2*width-1 : width] ;
        Result1 <= temp_sum[width-1 : 0] ;
             
    end
   
endmodule
